const dictionaries: Record<Lang, Record<DictKey, string>> = { bn, en };

const STORAGE_KEY = "lp-lang";

type LanguageContextValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
  t: (key: DictKey, values?: Record<string, string | number>) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

function readStoredLang(): Lang {
  if (typeof window === "undefined") return "bn";
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "bn" || stored === "en") return stored;
  } catch {
    /* storage can be unavailable in private mode */
  }
  return "bn";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* ignore unavailable storage */
    }
  }, []);

  const toggleLang = useCallback(() => {
    setLang(lang === "bn" ? "en" : "bn");
  }, [lang, setLang]);

  const t = useCallback(
    (key: DictKey, values?: Record<string, string | number>) => {
      const template = dictionaries[lang][key] ?? bn[key];
      if (!values) return template;
      return Object.entries(values).reduce(
        (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
        template,
      );
    },
    [lang],
  );

  const value = useMemo(
    () => ({ lang, setLang, toggleLang, t }),
    [lang, setLang, toggleLang, t],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useI18n must be used inside LanguageProvider");
  }
  return context;
}

const numberFormats: Record<Lang, Intl.NumberFormat> = {
  bn: new Intl.NumberFormat("bn-BD"),
  en: new Intl.NumberFormat("en-US"),
};

export function formatNumber(value: number, lang: Lang): string {
  return numberFormats[lang].format(value);
}

export function formatTaka(value: number, lang: Lang): string {
  return `৳${formatNumber(value, lang)}`;
}

const bengaliDigits = "০১২৩৪৫৬৭৮৯";

export function formatTwoDigits(value: number, lang: Lang): string {
  const padded = String(Math.max(0, value)).padStart(2, "0");
  if (lang === "en") return padded;
  return padded.replace(/\d/g, (digit) => bengaliDigits[Number(digit)]);
}

const dateTimeFormats: Record<Lang, Intl.DateTimeFormat> = {
  bn: new Intl.DateTimeFormat("bn-BD", { dateStyle: "medium", timeStyle: "short" }),
  en: new Intl.DateTimeFormat("en-GB", { dateStyle: "medium", timeStyle: "short" }),
};

export function formatDateTime(iso: string, lang: Lang): string {
  const value = new Date(iso);
  if (Number.isNaN(value.getTime())) return "—";
  return dateTimeFormats[lang].format(value);
}

export function roleName(
  role: { name_bn: string; name_en: string },
  lang: Lang,
): string {
  return lang === "bn" ? role.name_bn : role.name_en;
}
